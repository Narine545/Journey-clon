"""Generate the whale's smooth, unified rest mesh (requires numpy, scikit-image).
Run: python tools/generate_whale_mesh.py. X points towards the head; metres.
The runtime material animates the tail and provides lighting and emission.
"""
from pathlib import Path
import numpy as np
from skimage.measure import marching_cubes

step = 0.07
x = np.arange(-3.9, 3.35, step, dtype=np.float32)
y = np.arange(-1.5, 1.55, step, dtype=np.float32)
z = np.arange(-2.0, 2.05, step, dtype=np.float32)
X, Y, Z = np.meshgrid(x, y, z, indexing='ij')

def ell(cx, cy, cz, rx, ry, rz):
    a, b, c = X - cx, Y - cy, Z - cz
    k0 = np.sqrt((a/rx)**2 + (b/ry)**2 + (c/rz)**2)
    k1 = np.sqrt((a/rx**2)**2 + (b/ry**2)**2 + (c/rz**2)**2)
    return k0 * (k0 - 1.0) / np.maximum(k1, 1e-6)

def blend(a, b, k):
    h = np.clip(0.5 + 0.5*(b-a)/k, 0.0, 1.0)
    return b*(1-h) + a*h - k*h*(1-h)

# An elongated, tapered whale with a low back, a broad head and tail stock.
d = ell(0.0, 0.0, 0.0, 2.10, 0.88, 0.90)
for args, k in [((1.30, -0.05, 0, 1.15, 0.68, 0.80), .35),
                ((-1.60, -0.03, 0, 1.12, 0.48, 0.53), .55),
                ((-2.54, -0.03, 0, .62, .25, .30), .32),
                ((-.75, .75, 0, .40, .34, .12), .14)]:
    d = blend(d, ell(*args), k)
# Flippers and horizontal tail lobes, integrated into the body.
for sign in (-1, 1):
    d = blend(d, ell(-.15, -.30, sign*0.92, .63, .13, .92), .20)
    d = blend(d, ell(-3.05, -.02, sign*.55, .52, .12, .75), .18)
verts, faces, normals, _ = marching_cubes(d, 0.0, spacing=(step,step,step))
verts += np.array([x[0], y[0], z[0]])
# skimage normals point towards decreasing SDF; reverse them and the winding.
normals = -normals
out = Path('assets/creatures/whale.obj')
with out.open('w') as f:
    f.write('# Unified whale body; generated by tools/generate_whale_mesh.py\no Whale\n')
    for v in verts: f.write('v %.5f %.5f %.5f\n' % tuple(v))
    for n in normals: f.write('vn %.5f %.5f %.5f\n' % tuple(n))
    for a,b,c in faces:
        a,b,c = int(a)+1,int(b)+1,int(c)+1
        f.write(f'f {a}//{a} {c}//{c} {b}//{b}\n')
print(out, len(verts), len(faces))
